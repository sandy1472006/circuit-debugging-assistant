"""
netlist_parser.py - Structured graph representation G = (V, E),
SPICE netlist exporter, topology validation, and four-category error detection.
"""

import re
from typing import Dict, List, Tuple, Any, Optional

class Component:
    def __init__(
        self,
        ref: str,
        comp_type: str,
        value: float,
        unit: str,
        nodes: List[str],
        confidence: float = 1.0,
        uncertain: bool = False
    ):
        self.ref = ref                  # e.g. R1, C1, L1, VIN
        self.comp_type = comp_type      # RESISTOR, CAPACITOR, INDUCTOR, VOLTAGE_SOURCE, etc.
        self.value = float(value)
        self.unit = unit                # ohm, F, H, V, etc.
        self.nodes = [str(n) for n in nodes]
        self.confidence = float(confidence)
        self.uncertain = bool(uncertain)

    def to_dict(self) -> Dict[str, Any]:
        return {
            "ref": self.ref,
            "type": self.comp_type,
            "value": self.value,
            "unit": self.unit,
            "nodes": self.nodes,
            "confidence": self.confidence,
            "uncertain": self.uncertain
        }


class CircuitGraph:
    """
    Structured circuit graph representation G = (V, E)
    V: Electrical nets (nodes)
    E: Components connecting terminals to nets
    """
    def __init__(self, name: str = "Reconstructed Circuit"):
        self.name = name
        self.components: Dict[str, Component] = {}
        self.nodes: Dict[str, List[str]] = {} # node_name -> list of component refs

    def add_component(self, comp: Component):
        self.components[comp.ref] = comp
        for node in comp.nodes:
            if node not in self.nodes:
                self.nodes[node] = []
            self.nodes[node].append(comp.ref)

    def remove_component(self, ref: str):
        if ref in self.components:
            comp = self.components.pop(ref)
            for node in comp.nodes:
                if node in self.nodes and ref in self.nodes[node]:
                    self.nodes[node].remove(ref)

    def get_ground_node(self) -> Optional[str]:
        for n in self.nodes.keys():
            if n in ["0", "GND", "gnd", "ground", "GROUND"]:
                return n
        return None

    def to_dict(self) -> Dict[str, Any]:
        return {
            "name": self.name,
            "components": [c.to_dict() for c in self.components.values()],
            "nodes": {n: comps for n, comps in self.nodes.items()}
        }

    def to_spice_netlist(self) -> str:
        lines = [f"* SPICE Netlist generated by Circuit Debugging Assistant", f"* Circuit: {self.name}"]
        for comp in self.components.values():
            prefix = comp.ref[0].upper()
            nodes_str = " ".join(comp.nodes)
            lines.append(f"{comp.ref} {nodes_str} {comp.value}")
        lines.append(".op")
        lines.append(".end")
        return "\n".join(lines)


def validate_circuit_topology(graph: CircuitGraph, circuit_type: str = "") -> List[Dict[str, Any]]:
    """
    Performs comprehensive topology checking and returns structured findings
    classified into Categories A, B, C, D as defined in Section 6.
    """
    findings = []
    finding_counter = 1

    # Check 1: Missing Ground Reference (Category B)
    gnd_node = graph.get_ground_node()
    if not gnd_node:
        findings.append({
            "id": f"FIND-{finding_counter:03d}",
            "category": "Category B: Electrical topology & consistency",
            "component_or_net": "GND",
            "severity": "Critical",
            "evidence": "No reference node (0 or GND) found in circuit netlist.",
            "calculation": "G = (V, E) contains no potential reference node V_0 = 0V.",
            "expected_behavior": "A designated ground node is required to establish circuit potential references.",
            "observed_behavior": "All electrical nodes are floating without ground reference.",
            "recommended_correction": "Designate common return bus or negative rail as node '0' / 'GND'.",
            "confidence": 0.99,
            "status": "Confirmed"
        })
        finding_counter += 1

    # Check 2: Floating Nodes (Category B)
    for node, comps in graph.nodes.items():
        if node in ["0", "GND", "gnd"]:
            continue
        if len(comps) <= 1:
            findings.append({
                "id": f"FIND-{finding_counter:03d}",
                "category": "Category B: Electrical topology & consistency",
                "component_or_net": f"Net '{node}'",
                "severity": "Major",
                "evidence": f"Node '{node}' is connected to only {len(comps)} component terminal: {comps}.",
                "calculation": f"Degree(V_{node}) = {len(comps)} < 2",
                "expected_behavior": "Functional circuit nodes must connect at least two component terminals.",
                "observed_behavior": f"Dangling node with single connection to {comps}.",
                "recommended_correction": f"Check for missing wire or unconnected terminal on net '{node}'.",
                "confidence": 0.95,
                "status": "Confirmed"
            })
            finding_counter += 1

    # Check 3: Shorted Components (Category B)
    for comp in graph.components.values():
        if len(comp.nodes) >= 2 and comp.nodes[0] == comp.nodes[1]:
            findings.append({
                "id": f"FIND-{finding_counter:03d}",
                "category": "Category B: Electrical topology & consistency",
                "component_or_net": comp.ref,
                "severity": "Critical",
                "evidence": f"Both terminals of {comp.ref} are connected to the same net '{comp.nodes[0]}' creating a direct short.",
                "calculation": f"V({comp.nodes[0]}) - V({comp.nodes[1]}) = 0V identically.",
                "expected_behavior": "Component should bridge distinct potential nodes.",
                "observed_behavior": f"{comp.ref} is bypassed by a direct short circuit.",
                "recommended_correction": f"Remove unintended short across {comp.ref} terminals.",
                "confidence": 0.98,
                "status": "Confirmed"
            })
            finding_counter += 1

    # Check 4: Extraction Uncertainty (Category A)
    for comp in graph.components.values():
        if comp.uncertain or comp.confidence < 0.80:
            findings.append({
                "id": f"FIND-{finding_counter:03d}",
                "category": "Category A: Schematic & extraction issues",
                "component_or_net": comp.ref,
                "severity": "Minor",
                "evidence": f"Computer vision extraction confidence for {comp.ref} is {comp.confidence:.2f} (< 0.80).",
                "calculation": f"Confidence({comp.ref}) = {comp.confidence:.2f}",
                "expected_behavior": "Legible schematic text and clear symbol geometry.",
                "observed_behavior": f"Ambiguous symbol or unverified OCR text for {comp.ref}.",
                "recommended_correction": "Review and manually confirm extracted component parameters.",
                "confidence": comp.confidence,
                "status": "Unresolved"
            })
            finding_counter += 1

    # Check 5: Non-positive or Unrealistic Component Values (Category A / B)
    for comp in graph.components.values():
        if comp.value <= 0:
            findings.append({
                "id": f"FIND-{finding_counter:03d}",
                "category": "Category A: Schematic & extraction issues",
                "component_or_net": comp.ref,
                "severity": "Major",
                "evidence": f"Component {comp.ref} has non-physical value {comp.value} {comp.unit}.",
                "calculation": f"Value({comp.ref}) <= 0",
                "expected_behavior": "Passive components must have strictly positive real values.",
                "observed_behavior": f"Value is zero or negative ({comp.value}).",
                "recommended_correction": f"Enter a valid nominal value for {comp.ref}.",
                "confidence": 0.99,
                "status": "Confirmed"
            })
            finding_counter += 1

    return findings
